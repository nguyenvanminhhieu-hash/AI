def tbc_chan_dong_le(a):
    s = 0
    count = 0

    for i in range(1, len(a), 2):   # dòng lẻ
        for x in a[i]:
            if x % 2 == 0:
                s += x
                count += 1

    return s / count if count != 0 else 0

