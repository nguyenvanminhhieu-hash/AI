def sv_20_tuoi(ds):
    nam_ht = datetime.now().year

    print("\nSinh viên đủ 20 tuổi:")
    for sv in ds:
        if nam_ht - sv.nam_sinh == 20:
            print(sv.ma, sv.ten)

