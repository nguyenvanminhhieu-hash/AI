def tbc_bien(a):
    m = len(a)
    n = len(a[0])
    s = 0
    count = 0

    for i in range(m):
        for j in range(n):
            if i == 0 or i == m-1 or j == 0 or j == n-1:
                s += a[i][j]
                count += 1

    return s / count

# i) Tính trung bình tích các phần tử không thuộc biên.
def tbc_tich_trong(a):
    m = len(a)
    n = len(a[0])

    tich = 1
    count = 0

    for i in range(1, m-1):
        for j in range(1, n-1):
            tich *= a[i][j]
            count += 1

    return tich / count if count != 0 else 0

