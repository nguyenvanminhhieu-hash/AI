def cot_tich_nho_nhat(a):
    n = len(a[0])
    min_tich = float('inf')
    index = -1

    for j in range(n):
        tich = 1
        for i in range(len(a)):
            tich *= a[i][j]
        if tich < min_tich:
            min_tich = tich
            index = j

    return index, min_tich

